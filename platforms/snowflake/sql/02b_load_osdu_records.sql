-- Load the OSDU well and facility records the identity view reads (12_ontology_identity.sql, ADR 0047).
-- Prereq: the two Parquet files from
--   uv run python -m oag_semantic.platform_knowledge --export-osdu data/frozen data/frozen/osdu_flat
-- PUT to @OAG_FABLE.CANONICAL._STAGING (see README). Each holds RECORD_ID plus the key columns
-- owl:hasKey names (UWI; FACILITY_ID, FACILITY_TYPE). Same INFER_SCHEMA + COPY INTO as 02_load_canonical.sql.

USE SCHEMA OAG_FABLE.CANONICAL;

CREATE OR REPLACE TABLE OAG_FABLE.CANONICAL.OSDU_WELL USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@_STAGING/osdu_well.parquet', FILE_FORMAT => 'PARQUET_FMT')));
COPY INTO OAG_FABLE.CANONICAL.OSDU_WELL FROM '@_STAGING/osdu_well.parquet'
  FILE_FORMAT = (FORMAT_NAME = 'PARQUET_FMT') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

CREATE OR REPLACE TABLE OAG_FABLE.CANONICAL.OSDU_FACILITY USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@_STAGING/osdu_facility.parquet', FILE_FORMAT => 'PARQUET_FMT')));
COPY INTO OAG_FABLE.CANONICAL.OSDU_FACILITY FROM '@_STAGING/osdu_facility.parquet'
  FILE_FORMAT = (FORMAT_NAME = 'PARQUET_FMT') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT 'osdu_well' AS t, COUNT(*) AS n FROM OAG_FABLE.CANONICAL.OSDU_WELL
UNION ALL SELECT 'osdu_facility', COUNT(*) FROM OAG_FABLE.CANONICAL.OSDU_FACILITY;
